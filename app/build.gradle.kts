// 正式签名信息从项目根目录的 keystore.properties 读取（已在 .gitignore 中忽略，不入库）。
// 文件不存在时跳过 release 签名配置，debug 构建不受影响；打 release 前需先创建该文件。
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        FileInputStream(keystorePropertiesFile).use { load(it) }
    }
}

android {
    // namespace 是 R/BuildConfig 的生成包名，保持与源码 package 一致（org.example.myapplication），
    // 避免全量改动源码目录；应用对外身份以 applicationId 为准。
    namespace = "org.example.myapplication"
    compileSdk {
        version = release(36)
    }

    defaultConfig {
        applicationId = "com.personalagent.app"   // 正式包名（上架/安装身份，确定后不可再改）
        minSdk = 24
        targetSdk = 36
        versionCode = 3
        versionName = "1.2"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true       // R8 代码混淆与压缩
            isShrinkResources = true     // 资源压缩（需配合 minify 开启）
            signingConfig = signingConfigs.getByName("release")
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    kotlinOptions {
        jvmTarget = "11"
    }
    buildFeatures {
        compose = true
        buildConfig = true   // release 门控 Debug 页需要引用 BuildConfig.DEBUG
    }
}

